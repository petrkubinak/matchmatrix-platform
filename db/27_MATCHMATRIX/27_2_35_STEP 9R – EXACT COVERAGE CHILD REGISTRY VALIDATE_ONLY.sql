        'RUNTIME_TESTED',

        58,

        TIMESTAMPTZ '2026-09-29 09:57:36.098+02',

        'STEP 9G runtime evidence. '
        'API-Sports HB league 131 season 2024; '
        '132 API results and 132 verified DB matches. '
        'Canonical season_id intentionally unresolved.'
    );


    /* =====================================================
       5. VALIDATION INSERT – HISTORY_PREDICTION
       ===================================================== */

    INSERT INTO ops.source_entity_time_scope_coverage
    (
        coverage_id,
        scope_type,
        scope_key,
        canonical_league_id,
        canonical_season_id,
        source_competition_key,
        source_season_key,
        scope_status,
        audit_evidence_id,
        tested_at,
        notes
    )
    VALUES
    (
        2,

        'COMPETITION_SEASON',

        'league:24881|source_competition:131|season:2024',

        24881,

        NULL,

        '131',

        '2024',

        'RUNTIME_TESTED',

        58,

        TIMESTAMPTZ '2026-09-29 09:57:36.098+02',

        'STEP 9G runtime evidence. '
        'Historical fixtures scope validated for model-oriented use. '
        'Canonical season_id intentionally unresolved.'
    );


    /* =====================================================
       6. VALIDACE
       ===================================================== */

    SELECT COUNT(*)
    INTO v_rows
    FROM ops.source_entity_time_scope_coverage;


    SELECT COUNT(*)
    INTO v_bad_parent
    FROM ops.source_entity_time_scope_coverage d
    LEFT JOIN ops.source_entity_time_coverage p
      ON p.coverage_id = d.coverage_id
    WHERE p.coverage_id IS NULL;


    SELECT COUNT(*)
    INTO v_bad_evidence
    FROM ops.source_entity_time_scope_coverage d
    LEFT JOIN ops.source_audit_evidence e
      ON e.audit_evidence_id = d.audit_evidence_id
    WHERE e.audit_evidence_id IS NULL;


    SELECT COUNT(*)
    INTO v_bad_season
    FROM ops.source_entity_time_scope_coverage
    WHERE scope_type = 'COMPETITION_SEASON'
      AND (
           canonical_league_id IS NULL
           OR source_season_key IS NULL
           OR btrim(source_season_key) = ''
      );


    IF v_rows <> 2
       OR v_bad_parent <> 0
       OR v_bad_evidence <> 0
       OR v_bad_season <> 0
    THEN

        RAISE EXCEPTION
            'STEP 9R VALIDATION FAIL: rows=%, bad_parent=%, bad_evidence=%, bad_season=%',
            v_rows,
            v_bad_parent,
            v_bad_evidence,
            v_bad_season;

    END IF;


    RAISE NOTICE
        'STEP_9R_ROWS=%',
        v_rows;

    RAISE NOTICE
        'STEP_9R_SCOPE=HB/CORE/fixtures/league_24881/source_league_131/season_2024';

    RAISE NOTICE
        'STEP_9R_CANONICAL_SEASON=NULL_ALLOWED_AND_VALID';

    RAISE NOTICE
        'STEP_9R_VALIDATE bad_parent=%, bad_evidence=%, bad_season=%',
        v_bad_parent,
        v_bad_evidence,
        v_bad_season;


    /* =====================================================
       7. CLEANUP – VALIDATE ONLY
       ===================================================== */

    EXECUTE '
        DROP TABLE ops.source_entity_time_scope_coverage
    ';


    IF to_regclass(
        'ops.source_entity_time_scope_coverage'
    ) IS NOT NULL THEN

        RAISE EXCEPTION
            'STEP 9R CLEANUP FAIL: validation table zůstala v DB.';

