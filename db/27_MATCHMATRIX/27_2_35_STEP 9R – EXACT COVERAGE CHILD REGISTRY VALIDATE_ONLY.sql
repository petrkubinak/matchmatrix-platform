DECLARE
    v_rows              integer;
    v_bad_parent        integer;
    v_bad_evidence      integer;
    v_bad_season        integer;
BEGIN

    /* =====================================================
       1. COLLISION GUARD
       ===================================================== */

    IF to_regclass(
        'ops.source_entity_time_scope_coverage'
    ) IS NOT NULL THEN

        RAISE EXCEPTION
            'STEP 9R BLOCKED: ops.source_entity_time_scope_coverage již existuje.';
    END IF;


    /* =====================================================
       2. CREATE VALIDATION TABLE
       ===================================================== */

    EXECUTE $DDL$

        CREATE TABLE ops.source_entity_time_scope_coverage
        (
            scope_coverage_id
                bigint
                GENERATED BY DEFAULT AS IDENTITY
                PRIMARY KEY,

            coverage_id
                bigint
                NOT NULL,

            scope_type
                text
                NOT NULL,

            scope_key
                text
                NOT NULL,

            canonical_league_id
                integer
                NULL,

            canonical_season_id
                bigint
                NULL,

            source_competition_key
                text
                NULL,

            source_season_key
                text
                NULL,

            scope_from
                date
                NULL,

            scope_to
                date
                NULL,

            scope_status
                text
                NOT NULL,

            audit_evidence_id
                bigint
                NOT NULL,

            tested_at
                timestamptz
                NULL,

            is_active
                boolean
                NOT NULL
                DEFAULT true,

            notes
                text
                NULL,

            created_at
                timestamptz
                NOT NULL
                DEFAULT now(),

            updated_at
                timestamptz
                NOT NULL
                DEFAULT now(),


            CONSTRAINT fk_setsc_coverage
                FOREIGN KEY (coverage_id)
                REFERENCES ops.source_entity_time_coverage
                    (coverage_id),

            CONSTRAINT fk_setsc_league
                FOREIGN KEY (canonical_league_id)
                REFERENCES public.leagues
                    (id),

            CONSTRAINT fk_setsc_season
                FOREIGN KEY (canonical_season_id)
                REFERENCES public.seasons
                    (id),

            CONSTRAINT fk_setsc_evidence
                FOREIGN KEY (audit_evidence_id)
                REFERENCES ops.source_audit_evidence
                    (audit_evidence_id),


            CONSTRAINT uq_setsc_parent_scope
                UNIQUE
                (
                    coverage_id,
                    scope_key
                ),


            CONSTRAINT ck_setsc_scope_type_nonempty
                CHECK (
                    btrim(scope_type) <> ''
                ),

            CONSTRAINT ck_setsc_scope_key_nonempty
                CHECK (
                    btrim(scope_key) <> ''
                ),

            CONSTRAINT ck_setsc_status
                CHECK (
                    scope_status IN (
                        'UNKNOWN',
                        'PLANNED',
                        'TECH_READY',
                        'RUNTIME_TESTED',
                        'CONFIRMED',
                        'BLOCKED'
                    )
                ),

            CONSTRAINT ck_setsc_date_range
                CHECK (
                    scope_from IS NULL
                    OR scope_to IS NULL
                    OR scope_from <= scope_to
                ),

            /*
            Pro COMPETITION_SEASON musí existovat:
            - canonical liga
            - source season key

            Canonical season_id zatím povinný NENÍ.
            */
            CONSTRAINT ck_setsc_competition_season
                CHECK (
                    scope_type <> 'COMPETITION_SEASON'
                    OR (
                        canonical_league_id IS NOT NULL
                        AND source_season_key IS NOT NULL
                        AND btrim(source_season_key) <> ''
                    )
                )
        )

    $DDL$;


    /* =====================================================
       3. INDEXY
       ===================================================== */

    EXECUTE '
        CREATE INDEX ix_setsc_coverage
        ON ops.source_entity_time_scope_coverage
        (coverage_id)
    ';

    EXECUTE '
        CREATE INDEX ix_setsc_league
        ON ops.source_entity_time_scope_coverage
        (canonical_league_id)
    ';

    EXECUTE '
        CREATE INDEX ix_setsc_season
        ON ops.source_entity_time_scope_coverage
        (canonical_season_id)
    ';

    EXECUTE '
        CREATE INDEX ix_setsc_evidence
        ON ops.source_entity_time_scope_coverage
        (audit_evidence_id)
    ';


    /* =====================================================
       4. VALIDATION INSERT – HISTORY_FAN
       ===================================================== */

    INSERT INTO ops.source_entity_time_scope_coverage
    (
        coverage_id,
        scope_type,
        scope_key,
        canonical_league_id,
        canonical_season_id,
        source_competition_key,
