    INTO v_column_count
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'match_provider_map';

    SELECT COUNT(*)
    INTO v_constraint_count
    FROM pg_constraint
    WHERE conrelid = 'public.match_provider_map'::regclass;

    SELECT COUNT(*)
    INTO v_index_count
    FROM pg_indexes
    WHERE schemaname = 'public'
      AND tablename = 'match_provider_map';

    SELECT COUNT(*)
    INTO v_trigger_count
    FROM pg_trigger
    WHERE tgrelid = 'public.match_provider_map'::regclass
      AND NOT tgisinternal;

    SELECT COUNT(*)
    INTO v_row_count
    FROM public.match_provider_map;

    IF v_column_count <> 17 THEN
        RAISE EXCEPTION
            'APPLY_FAILED: Očekáváno 17 sloupců, nalezeno %.',
            v_column_count;
    END IF;

    IF v_constraint_count <> 12 THEN
        RAISE EXCEPTION
            'APPLY_FAILED: Očekáváno 12 constraints, nalezeno %.',
            v_constraint_count;
    END IF;

    IF v_index_count <> 6 THEN
        RAISE EXCEPTION
            'APPLY_FAILED: Očekáváno 6 indexů, nalezeno %.',
            v_index_count;
    END IF;

