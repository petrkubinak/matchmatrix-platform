-- 2. POVINNÉ PŘEDBĚŽNÉ KONTROLY
-------------------------------------------------------------------------------

DO $precheck$
DECLARE
    v_match_id_type text;
BEGIN
    IF to_regclass('public.matches') IS NULL THEN
        RAISE EXCEPTION
            'APPLY_FAILED: Tabulka public.matches neexistuje.';
    END IF;

    IF to_regclass('public.match_provider_map') IS NOT NULL THEN
        RAISE EXCEPTION
            'APPLY_FAILED: Tabulka public.match_provider_map již existuje.';
    END IF;

    IF to_regprocedure(
        'public.fn_match_provider_map_touch()'
    ) IS NOT NULL THEN
        RAISE EXCEPTION
            'APPLY_FAILED: Funkce public.fn_match_provider_map_touch již existuje.';
    END IF;

    SELECT format_type(a.atttypid, a.atttypmod)
    INTO v_match_id_type
    FROM pg_attribute a
    WHERE a.attrelid = 'public.matches'::regclass
      AND a.attname = 'id'
      AND a.attnum > 0
      AND NOT a.attisdropped;

    IF v_match_id_type IS NULL THEN
        RAISE EXCEPTION
            'APPLY_FAILED: Sloupec public.matches.id nebyl nalezen.';
    END IF;

    IF v_match_id_type <> 'integer' THEN
        RAISE EXCEPTION
            'APPLY_FAILED: Očekáván typ integer, nalezen typ %.',
            v_match_id_type;
    END IF;

    RAISE NOTICE
        'OK: public.matches.id používá potvrzený datový typ integer.';
END
$precheck$;

-------------------------------------------------------------------------------
-- 3. CÍLOVÁ TABULKA
-------------------------------------------------------------------------------

CREATE TABLE public.match_provider_map
(
    id bigint GENERATED BY DEFAULT AS IDENTITY,

    match_id integer NOT NULL,

    provider text NOT NULL,
    provider_match_id text NOT NULL,

    identity_origin text NOT NULL DEFAULT 'PROVIDER',
    external_id_kind text NOT NULL DEFAULT 'NATIVE',

    mapping_status text NOT NULL DEFAULT 'ACTIVE',
    is_primary boolean NOT NULL DEFAULT false,

    confidence_score numeric(5,2) NOT NULL DEFAULT 100.00,

    source_record_hash text,

    first_seen_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    last_seen_at timestamptz NOT NULL DEFAULT clock_timestamp(),

    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,

    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),

    created_by text NOT NULL DEFAULT current_user,
    updated_by text NOT NULL DEFAULT current_user,

    CONSTRAINT pk_match_provider_map
        PRIMARY KEY (id),

    CONSTRAINT fk_match_provider_map_match
        FOREIGN KEY (match_id)
        REFERENCES public.matches(id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT ck_mpm_provider_not_blank
        CHECK (length(btrim(provider)) > 0),

    CONSTRAINT ck_mpm_provider_match_id_not_blank
        CHECK (length(btrim(provider_match_id)) > 0),

    CONSTRAINT ck_mpm_identity_origin
        CHECK (
            identity_origin IN (
                'PROVIDER',
                'SOURCE',
                'ADAPTER',
                'INTERNAL'
            )
        ),

    CONSTRAINT ck_mpm_external_id_kind
        CHECK (
            external_id_kind IN (
                'NATIVE',
                'DERIVED',
                'HASH'
            )
        ),

    CONSTRAINT ck_mpm_mapping_status
        CHECK (
            mapping_status IN (
                'ACTIVE',
                'REVIEW',
                'HOLD',
                'SUPERSEDED',
                'REJECTED'
            )
        ),

    CONSTRAINT ck_mpm_primary_must_be_active
        CHECK (
            is_primary = false
            OR mapping_status = 'ACTIVE'
        ),

    CONSTRAINT ck_mpm_confidence_score
        CHECK (
            confidence_score >= 0.00
            AND confidence_score <= 100.00
        ),

    CONSTRAINT ck_mpm_seen_time_order
        CHECK (
            first_seen_at <= last_seen_at
        ),

    CONSTRAINT ck_mpm_source_record_hash
        CHECK (
            source_record_hash IS NULL
            OR source_record_hash ~ '^[0-9A-Fa-f]{64}$'
        ),

    CONSTRAINT ck_mpm_metadata_object
        CHECK (
            jsonb_typeof(metadata) = 'object'
        )
);

-------------------------------------------------------------------------------
-- 4. UNIKÁTNÍ PRAVIDLA A INDEXY
-------------------------------------------------------------------------------

CREATE UNIQUE INDEX uq_mpm_provider_identity
    ON public.match_provider_map (
        provider,
        provider_match_id
    );

CREATE UNIQUE INDEX uq_mpm_one_active_primary
    ON public.match_provider_map (match_id)
    WHERE is_primary = true
      AND mapping_status = 'ACTIVE';

CREATE UNIQUE INDEX uq_mpm_provider_source_hash
    ON public.match_provider_map (
        provider,
        source_record_hash
    )
    WHERE source_record_hash IS NOT NULL;

CREATE INDEX ix_mpm_match_id
    ON public.match_provider_map (match_id);

CREATE INDEX ix_mpm_mapping_status
    ON public.match_provider_map (
        mapping_status,
        provider
    );

-------------------------------------------------------------------------------
-- 5. AUDITNÍ FUNKCE
-------------------------------------------------------------------------------

CREATE FUNCTION public.fn_match_provider_map_touch()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
    NEW.updated_at := clock_timestamp();
    NEW.updated_by := current_user;

    IF NEW.last_seen_at < OLD.last_seen_at THEN
        RAISE EXCEPTION
            'last_seen_at nesmí být starší než předchozí hodnota.';
    END IF;

    RETURN NEW;
END
$function$;

CREATE TRIGGER trg_match_provider_map_touch
BEFORE UPDATE
ON public.match_provider_map
FOR EACH ROW
EXECUTE FUNCTION public.fn_match_provider_map_touch();

