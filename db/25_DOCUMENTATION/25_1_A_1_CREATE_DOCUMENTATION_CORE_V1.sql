-- 10. POHLED KONTROLY INTEGRITY
-- ============================================================================

CREATE OR REPLACE VIEW documentation.v_document_integrity_v1 AS
WITH version_counts AS (
    SELECT
        document_pk,
        count(*) AS version_count,
        count(*) FILTER (WHERE is_current = true) AS current_version_count
    FROM documentation.document_versions
    GROUP BY document_pk
)
SELECT
    d.document_pk,
    d.document_id,
    d.title,
    d.current_status,
    d.current_version_label,
    d.repo_relative_path,
    d.is_active,
    coalesce(vc.version_count, 0) AS version_count,
    coalesce(vc.current_version_count, 0) AS current_version_count,
    CASE
        WHEN d.repo_relative_path IS NULL
            THEN 'MISSING_REPOSITORY_PATH'
        WHEN d.canonical_filename IS NULL
            THEN 'MISSING_CANONICAL_FILENAME'
        WHEN d.is_active
             AND coalesce(vc.version_count, 0) = 0
            THEN 'MISSING_VERSION'
        WHEN d.is_active
             AND coalesce(vc.current_version_count, 0) = 0
            THEN 'MISSING_CURRENT_VERSION'
        WHEN coalesce(vc.current_version_count, 0) > 1
            THEN 'MULTIPLE_CURRENT_VERSIONS'
        ELSE 'OK'
    END AS integrity_status
FROM documentation.documents d
LEFT JOIN version_counts vc
  ON vc.document_pk = d.document_pk;

COMMENT ON VIEW documentation.v_document_integrity_v1 IS
'Kontrolní pohled ověřující základní úplnost a konzistenci registru dokumentů.';

