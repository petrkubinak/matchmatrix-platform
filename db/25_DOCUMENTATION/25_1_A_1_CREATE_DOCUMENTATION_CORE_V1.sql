CREATE OR REPLACE FUNCTION documentation.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
    NEW.updated_at := clock_timestamp();
    RETURN NEW;
END;
$function$;

COMMENT ON FUNCTION documentation.set_updated_at() IS
'Nastavuje updated_at při každé změně řádku dokumentu.';

DO $do$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_trigger
        WHERE tgname = 'trg_documentation_documents_updated_at'
          AND tgrelid = 'documentation.documents'::regclass
    ) THEN
        CREATE TRIGGER trg_documentation_documents_updated_at
        BEFORE UPDATE
        ON documentation.documents
        FOR EACH ROW
        EXECUTE FUNCTION documentation.set_updated_at();
    END IF;
END;
$do$;

