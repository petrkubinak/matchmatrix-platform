-- 12. VERIFIKACE PŘED COMMIT
-- ============================================================================

DO $do$
DECLARE
    v_table_count integer;
    v_view_count  integer;
BEGIN
    SELECT count(*)
    INTO v_table_count
    FROM information_schema.tables
    WHERE table_schema = 'documentation'
      AND table_type = 'BASE TABLE';

    SELECT count(*)
    INTO v_view_count
    FROM information_schema.views
    WHERE table_schema = 'documentation';

    IF v_table_count < 6 THEN
        RAISE EXCEPTION
            'Documentation schema verification failed. Expected at least 6 tables, found %.',
            v_table_count;
    END IF;

    IF v_view_count < 2 THEN
        RAISE EXCEPTION
            'Documentation schema verification failed. Expected at least 2 views, found %.',
            v_view_count;
    END IF;
END;
$do$;

COMMIT;

