    SELECT
        table_name AS object_name,
        'TABLE'::text AS object_type
    FROM information_schema.tables
    WHERE table_schema = 'documentation'
      AND table_type = 'BASE TABLE'

    UNION ALL

    SELECT
        table_name AS object_name,
        'VIEW'::text AS object_type
    FROM information_schema.views
    WHERE table_schema = 'documentation'
) objects;

